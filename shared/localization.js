export function isSupportedLanguage(language) {
  return SUPPORTED_LANGUAGES.includes(language)
}

export function translate(language, message, parameters = {}) {
  const localized = language === 'zh' && Object.hasOwn(CHINESE_MESSAGES, message)
    ? CHINESE_MESSAGES[message]
    : message
  return localized.replace(/\{(\w+)\}/g, (placeholder, key) => (
    Object.hasOwn(parameters, key) ? String(parameters[key]) : placeholder
  ))
}
